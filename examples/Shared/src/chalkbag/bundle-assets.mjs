#!/usr/bin/env node
// Bundle a representative smichov wall + hold subset + sky into the RNF ExpoExample harness.
// Emits Shared/src/chalkbag/wallData.ts with literal require()s + hold/route metadata.
import fs from 'node:fs'
import path from 'node:path'

const ROOT = '/home/xiaoxiae/Documents/Education/School/MatFyz/Studium/Bakalářské/4. semestr/Ročníkový projekt (RP)/přednáška/Climber Tools/Climbuddy'
const FIX = path.join(ROOT, 'backend/fixtures/smichov')
const WT = path.join(ROOT, '../Climbuddy-filament-mvp/app/public/filament-mvp')
const SHARED_ASSETS = path.join(ROOT, 'forks/react-native-filament/examples/Shared/assets')
const EE_ASSETS = path.join(ROOT, 'forks/react-native-filament/examples/ExpoExample/assets')
const OUT_TS = path.join(ROOT, 'forks/react-native-filament/examples/Shared/src/chalkbag/wallData.ts')

// --- GLB bbox probe (parse JSON chunk + POSITION accessor min/max) ---
function glbBBox(file) {
  const buf = fs.readFileSync(file)
  if (buf.readUInt32LE(0) !== 0x46546c67) return null // 'glTF'
  const jsonLen = buf.readUInt32LE(12)
  const json = JSON.parse(buf.slice(20, 20 + jsonLen).toString('utf8'))
  let min = [Infinity, Infinity, Infinity], max = [-Infinity, -Infinity, -Infinity]
  for (const m of json.meshes ?? [])
    for (const p of m.primitives ?? []) {
      const a = json.accessors?.[p.attributes?.POSITION]
      if (a?.min && a?.max) {
        for (let i = 0; i < 3; i++) { min[i] = Math.min(min[i], a.min[i]); max[i] = Math.max(max[i], a.max[i]) }
      }
    }
  return { min, max, center: min.map((v, i) => (v + max[i]) / 2) }
}

const holdsMeta = JSON.parse(fs.readFileSync(path.join(FIX, 'holds/metadata.json'), 'utf8'))
const routes = JSON.parse(fs.readFileSync(path.join(FIX, 'routes.json'), 'utf8'))
const byId = new Map(holdsMeta.map((h) => [h.frontend_id, h]))

// probe wall + first hold for coordinate-frame determination
console.log('=== WALL bbox ===', JSON.stringify(glbBBox(path.join(FIX, 'wall/wall.glb'))))
const firstHold = holdsMeta[0]
console.log('=== HOLD', firstHold.frontend_id, 'metadata.center=', firstHold.center)
console.log('=== HOLD bbox ===', JSON.stringify(glbBBox(path.join(FIX, `holds/${firstHold.frontend_id}.glb`))))

// --- pick routes greedily until union of holds (that exist as GLBs) reaches ~36 ---
const TARGET = 36
const picked = []
const union = new Set()
for (const r of routes) {
  if (union.size >= TARGET) break
  const have = r.holds.filter((id) => byId.has(id) && fs.existsSync(path.join(FIX, `holds/${id}.glb`)))
  if (have.length < 4) continue
  picked.push({ id: r.id, name: r.name, circuit: r.circuit, grade: r.grade, holdIds: have })
  have.forEach((id) => union.add(id))
}
const holdIds = [...union]
console.log(`picked ${picked.length} routes, ${holdIds.length} unique holds`)

// --- copy assets (flat, cb_ prefix) into BOTH asset dirs ---
const copy = (src, name) => {
  for (const dir of [SHARED_ASSETS, EE_ASSETS]) fs.copyFileSync(src, path.join(dir, name))
  return name
}
// NOTE: wall.glb uses EXT_texture_webp → Filament native gltfio SIGSEGVs in
// ResourceLoader::createTextures (it can't decode WebP). cb_wall.glb is produced
// SEPARATELY by re-encoding WebP→PNG (dwebp + @gltf-transform). This script does
// NOT copy the raw wall.glb so it won't clobber the good PNG version on re-run.
// To (re)produce cb_wall.glb: decode each WebP image via dwebp, setImage/setMimeType
// 'image/png', dispose the EXT_texture_webp extension, write to both asset dirs.
if (process.env.CB_COPY_RAW_WALL) copy(path.join(FIX, 'wall/wall.glb'), 'cb_wall.glb')
copy(path.join(WT, 'sky_gradient_strong.ktx'), 'cb_sky_strong.ktx')
copy(path.join(WT, 'sky_gradient.ktx'), 'cb_sky.ktx')
for (const id of holdIds) copy(path.join(FIX, `holds/${id}.glb`), `cb_${id}.glb`)

// --- codegen wallData.ts ---
const holdEntries = holdIds.map((id) => {
  const h = byId.get(id)
  return `  { id: ${JSON.stringify(id)}, glb: require('@assets/cb_${id}.glb'), center: [${h.center.join(', ')}], normal: [${h.normal.join(', ')}], color: ${JSON.stringify(h.color)} },`
}).join('\n')
const routeEntries = picked.map((r) =>
  `  { id: ${JSON.stringify(r.id)}, name: ${JSON.stringify(r.name ?? null)}, circuit: ${JSON.stringify(r.circuit ?? null)}, holdIds: ${JSON.stringify(r.holdIds)} },`
).join('\n')

const ts = `// AUTO-GENERATED by scripts bundling (do not edit by hand).
// Representative smichov wall + ${holdIds.length}-hold subset for the Chalkbag native rendering playground.
import type { Float3 } from 'react-native-filament'

export type HoldDef = { id: string; glb: number; center: Float3; normal: Float3; color: string }
export type RouteDef = { id: string; name: string | null; circuit: string | null; holdIds: string[] }

export const wallGlb = require('@assets/cb_wall.glb') as number
export const skyStrongKtx = require('@assets/cb_sky_strong.ktx') as number
export const skyChalkKtx = require('@assets/cb_sky.ktx') as number

export const holds: HoldDef[] = [
${holdEntries}
]

export const routes: RouteDef[] = [
${routeEntries}
]
`
fs.mkdirSync(path.dirname(OUT_TS), { recursive: true })
fs.writeFileSync(OUT_TS, ts)
console.log('wrote', OUT_TS, `(${holdIds.length} holds, ${picked.length} routes)`)
